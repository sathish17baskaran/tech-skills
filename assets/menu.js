/* Left-side menu: every section page and its topics, collapsible.
   Data comes from assets/menu-data.js (window.SITE_MENU), generated by tools/build-menu.ps1. */
(function () {
  'use strict';
  var data = window.SITE_MENU;
  if (!data) return;
  var KEY = 'tcp-side-open';
  var wide = window.matchMedia('(min-width: 1100px)');
  var here = decodeURIComponent(location.pathname.split('/').pop()) || 'index.html';

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  var side = el('aside', 'side');
  side.setAttribute('aria-label', 'All topics');
  var head = el('div', 'side-head');
  var home = el('a', 'side-home', 'Tech Concepts Prep');
  home.href = 'index.html';
  var close = el('button', 'side-x', '\u00d7');
  close.type = 'button';
  close.title = 'Hide menu';
  head.appendChild(home);
  head.appendChild(close);
  side.appendChild(head);

  var tools = el('div', 'side-tools');
  var filter = el('input', 'side-filter');
  filter.type = 'search';
  filter.placeholder = 'Search topics and keywords\u2026';
  filter.setAttribute('aria-label', 'Search topics');
  var expand = el('button', null, 'Expand all');
  var collapse = el('button', null, 'Collapse all');
  expand.type = collapse.type = 'button';
  tools.appendChild(filter);
  var btns = el('div', 'side-btns');
  btns.appendChild(expand);
  btns.appendChild(collapse);
  tools.appendChild(btns);
  var quick = el('a', 'side-quick', '\u26a1 Last-minute revision');
  quick.href = 'revise.html';
  if (here === 'revise.html') quick.classList.add('on');
  tools.appendChild(quick);
  side.appendChild(tools);

  var list = el('nav', 'side-list');
  var groups = [];
  var ctxs = [];
  var activeLinks = {};
  /* Context groups (e.g. "APIs & integration") stay open unless the reader closed them. */
  var CTX_KEY = 'tcp-ctx-closed';
  var closed = [];
  try { closed = JSON.parse(localStorage.getItem(CTX_KEY) || '[]'); } catch (e) {}
  function saveCtx() {
    closed = ctxs.filter(function (c) { return !c.open; }).map(function (c) { return c.dataset.name; });
    try { localStorage.setItem(CTX_KEY, JSON.stringify(closed)); } catch (e) {}
  }
  /* Each context group has a colour theme (style.css [data-theme]), keyed by its first word: "APIs & integration" -> "apis". */
  function theme(g) { return String(g).split(/[^A-Za-z]/)[0].toLowerCase(); }
  var ctx = null, ctxBody = null;
  data.forEach(function (p) {
    if (!ctx || ctx.dataset.name !== p.g) {
      ctx = el('details', 'side-ctx');
      ctx.dataset.name = p.g;
      ctx.dataset.theme = theme(p.g);
      ctx.open = closed.indexOf(p.g) < 0;
      var cs = el('summary');
      cs.appendChild(el('span', 'side-ctx-t', p.g));
      cs.appendChild(el('span', 'side-ctx-n', '0'));
      ctx.appendChild(cs);
      ctxBody = el('div', 'side-ctx-body');
      ctx.appendChild(ctxBody);
      ctx.addEventListener('toggle', function () { if (!filter.value) saveCtx(); });
      list.appendChild(ctx);
      ctxs.push(ctx);
    }
    var count = ctx.querySelector('.side-ctx-n');
    count.textContent = String(+count.textContent + 1);
    var g = el('details', 'side-grp');
    if (p.f === here) { g.open = true; g.classList.add('current'); ctx.open = true; ctx.classList.add('has-current'); document.body.classList.add('in-menu'); document.body.dataset.theme = theme(p.g); }
    var sum = el('summary');
    var a = el('a', 'side-page');
    a.href = p.f;
    a.appendChild(el('span', 'side-num', p.n));
    a.appendChild(document.createTextNode(p.t));
    sum.appendChild(a);
    g.appendChild(sum);
    var ul = el('ul');
    p.s.forEach(function (s) {
      var li = el('li');
      var link = el('a', null, s[1]);
      link.href = p.f + '#' + s[0];
      if (p.f === here) activeLinks[s[0]] = link;
      li.appendChild(link);
      ul.appendChild(li);
    });
    g.appendChild(ul);
    ctxBody.appendChild(g);
    groups.push(g);
  });
  side.appendChild(list);
  document.body.insertBefore(side, document.body.firstChild);
  /* Roadmap cards and learning-path chips ("05 Caching") take their page's group colour. */
  document.querySelectorAll('a.sec-card').forEach(function (a) {
    var p = data.filter(function (x) { return x.f === a.getAttribute('href'); })[0];
    if (p) a.dataset.theme = theme(p.g);
  });
  document.querySelectorAll('#path .flow .n').forEach(function (n) {
    var p = data.filter(function (x) { return n.textContent.indexOf(x.n + ' ') === 0; })[0];
    if (p) n.dataset.theme = theme(p.g);
  });

  var shade = el('div', 'side-shade');
  document.body.appendChild(shade);

  var toggle = el('button', 'side-toggle', '\u2630');
  toggle.type = 'button';
  toggle.title = 'Show or hide the topics menu';
  toggle.setAttribute('aria-label', 'Toggle topics menu');
  document.body.appendChild(toggle);

  function setOpen(open, remember) {
    document.body.classList.toggle('side-open', open);
    toggle.setAttribute('aria-expanded', String(open));
    if (remember && wide.matches) { try { localStorage.setItem(KEY, open ? '1' : '0'); } catch (e) {} }
  }
  function initial() {
    var saved = null;
    try { saved = localStorage.getItem(KEY); } catch (e) {}
    setOpen(wide.matches ? saved !== '0' : false, false);
  }
  initial();
  if (wide.addEventListener) wide.addEventListener('change', initial);
  toggle.addEventListener('click', function () { setOpen(!document.body.classList.contains('side-open'), true); });
  close.addEventListener('click', function () { setOpen(false, true); });
  shade.addEventListener('click', function () { setOpen(false, false); });
  list.addEventListener('click', function (e) {
    if (e.target.closest('a') && !wide.matches) setOpen(false, false);
  });

  expand.addEventListener('click', function () {
    ctxs.forEach(function (c) { c.open = true; });
    groups.forEach(function (g) { g.open = true; });
  });
  collapse.addEventListener('click', function () { groups.forEach(function (g) { g.open = false; }); });

  /* Search: matches topic and page titles, plus each topic's keywords, 30-second answer, key points and
     flashcard questions from assets/revise/NN.js (loaded on first use). A result opens topic.html,
     which puts everything on that topic on one page for last-minute prep. */
  var results = el('div', 'side-results');
  results.hidden = true;
  side.insertBefore(results, list);
  var requested = false, queued = false;
  function loadData() {
    if (requested) return;
    requested = true;
    data.forEach(function (p) {
      if ((window.REVISE || {})[p.n]) return;
      var s = document.createElement('script');
      s.src = 'assets/revise/' + p.n + '.js';
      s.onload = function () {
        if (queued || !filter.value.trim()) return;
        queued = true;
        requestAnimationFrame(function () { queued = false; search(); });
      };
      document.head.appendChild(s);
    });
  }
  function plain(s) { return String(s || '').replace(/<[^>]+>/g, ' ').toLowerCase(); }
  function search() {
    var q = filter.value.trim().toLowerCase();
    list.hidden = btns.hidden = !!q;
    results.hidden = !q;
    results.innerHTML = '';
    if (!q) return;
    var words = q.split(/\s+/), R = window.REVISE || {}, hits = [];
    data.forEach(function (p, pi) {
      p.s.forEach(function (s, si) {
        var d = (R[p.n] && R[p.n].sections && R[p.n].sections[s[0]]) || {};
        var title = s[1].toLowerCase(), keys = plain((d.k || []).join(' | ')), pageT = (p.n + ' ' + p.t).toLowerCase();
        var body = plain([d.say].concat(d.p || [], (d.f || []).map(function (f) { return f[0]; })).join(' '));
        var score = 0;
        for (var i = 0; i < words.length; i++) {
          var w = words[i], at = title.indexOf(w);
          var sc = at >= 0 ? (at === 0 || /\W/.test(title.charAt(at - 1)) ? 12 : 8) : keys.indexOf(w) >= 0 ? 5 : pageT.indexOf(w) >= 0 ? 3 : body.indexOf(w) >= 0 ? 1 : 0;
          if (!sc) { score = 0; break; }
          score += sc;
        }
        if (score) hits.push({ p: p, s: s, k: (d.k || []).filter(function (k) { return words.some(function (w) { return k.toLowerCase().indexOf(w) >= 0; }); }), score: score, order: pi * 1000 + si });
      });
    });
    hits.sort(function (a, b) { return b.score - a.score || a.order - b.order; });
    results.appendChild(el('div', 'side-results-h', hits.length ? hits.length + (hits.length === 1 ? ' topic' : ' topics') + ' \u00b7 pick one for a last-minute summary' : 'No topics match. Try a shorter or different word.'));
    hits.slice(0, 40).forEach(function (h) {
      var a = el('a', 'side-hit');
      a.href = 'topic.html?p=' + h.p.n + '&s=' + encodeURIComponent(h.s[0]);
      a.dataset.theme = theme(h.p.g);
      a.appendChild(el('span', 'side-hit-t', h.s[1]));
      a.appendChild(el('span', 'side-hit-p', h.p.n + ' \u00b7 ' + h.p.t));
      if (h.k.length) {
        var ks = el('span', 'side-hit-k');
        h.k.slice(0, 3).forEach(function (k) { ks.appendChild(el('i', null, k.replace(/<[^>]+>/g, ''))); });
        a.appendChild(ks);
      }
      results.appendChild(a);
    });
  }
  filter.addEventListener('focus', loadData);
  filter.addEventListener('input', function () { loadData(); search(); });
  filter.addEventListener('keydown', function (e) {
    var first = results.querySelector('.side-hit');
    if (e.key === 'Enter' && first) location.href = first.href;
    else if (e.key === 'ArrowDown' && first) { e.preventDefault(); first.focus(); }
  });
  results.addEventListener('keydown', function (e) {
    var a = e.target.closest('.side-hit');
    if (!a || (e.key !== 'ArrowDown' && e.key !== 'ArrowUp')) return;
    e.preventDefault();
    var next = e.key === 'ArrowDown' ? a.nextElementSibling : a.previousElementSibling;
    if (next && next.classList.contains('side-hit')) next.focus(); else if (e.key === 'ArrowUp') filter.focus();
  });

  var cur = list.querySelector('.side-ctx.has-current');
  function showCurrent() { if (cur && !filter.value) list.scrollTop += cur.getBoundingClientRect().top - list.getBoundingClientRect().top - 8; }
  showCurrent();
  toggle.addEventListener('click', function () { setTimeout(showCurrent, 50); });

  /* Highlight the topic currently on screen and keep it visible in the menu. */
  var sections = Array.prototype.filter.call(document.querySelectorAll('section[id]'), function (s) { return activeLinks[s.id]; });
  if (sections.length) {
    var current = null, queued = false;
    var spy = function () {
      queued = false;
      var best = sections[0];
      sections.forEach(function (s) { if (s.getBoundingClientRect().top < window.innerHeight * 0.35) best = s; });
      if (best === current) return;
      if (current) activeLinks[current.id].classList.remove('active');
      current = best;
      var link = activeLinks[best.id];
      link.classList.add('active');
      var lr = link.getBoundingClientRect(), sr = list.getBoundingClientRect();
      if (lr.top < sr.top || lr.bottom > sr.bottom) list.scrollTop += lr.top - sr.top - sr.height / 3;
    };
    window.addEventListener('scroll', function () {
      if (!queued) { queued = true; requestAnimationFrame(spy); }
    }, { passive: true });
    spy();
  }
})();
