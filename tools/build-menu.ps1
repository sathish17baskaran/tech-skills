# Regenerates assets/menu-data.js (the left-side topics menu) from every NN-*.html page,
# and makes sure each page loads the menu scripts. Run after adding or renaming pages or sections:
#   powershell -ExecutionPolicy Bypass -File tools\build-menu.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object Text.UTF8Encoding $false
Add-Type -AssemblyName System.Web

function Clean([string]$html) { [System.Web.HttpUtility]::HtmlDecode(($html -replace '<[^>]+>', '')).Trim() }

$menu = @()
foreach ($file in Get-ChildItem $root -Filter '*.html' | Where-Object { $_.Name -match '^\d{2}-' -and -not ([IO.File]::ReadAllText($_.FullName) -match 'http-equiv="refresh"') } | Sort-Object Name) {
  $html = [IO.File]::ReadAllText($file.FullName)
  $title = [regex]::Match($html, '<title>\d{2}\s*\S\s*(.*?)\s*\|').Groups[1].Value
  $toc = [regex]::Match($html, '<div class="toc">([\s\S]*?)</div>').Groups[1].Value
  $topics = @(foreach ($m in [regex]::Matches($toc, '<a href="#([^"]+)"[^>]*>([\s\S]*?)</a>')) { , @($m.Groups[1].Value, (Clean $m.Groups[2].Value)) })
  $menu += [ordered]@{ f = $file.Name; n = $file.Name.Substring(0, 2); t = (Clean $title); s = $topics }

  # Load the menu on every page (before app.js).
  if ($html -notmatch 'assets/menu\.js') {
    $tags = '<script src="assets/menu-data.js"></script>' + "`r`n" + '<script src="assets/menu.js"></script>' + "`r`n"
    $html = $html.Replace('<script src="assets/app.js"></script>', $tags + '<script src="assets/app.js"></script>')
    [IO.File]::WriteAllText($file.FullName, $html, $utf8)
  }
}
$index = Join-Path $root 'index.html'
$ih = [IO.File]::ReadAllText($index)
if ($ih -notmatch 'assets/menu\.js') {
  $tags = '<script src="assets/menu-data.js"></script>' + "`r`n" + '<script src="assets/menu.js"></script>' + "`r`n"
  [IO.File]::WriteAllText($index, $ih.Replace('<script src="assets/app.js"></script>', $tags + '<script src="assets/app.js"></script>'), $utf8)
}

$json = ConvertTo-Json -InputObject $menu -Depth 5 -Compress
$js = "/* Generated by tools/build-menu.ps1 - do not edit by hand. */`r`nwindow.SITE_MENU = $json;`r`n"
[IO.File]::WriteAllText((Join-Path $root 'assets\menu-data.js'), $js, $utf8)
"menu: $($menu.Count) pages, $(($menu | ForEach-Object { $_.s.Count } | Measure-Object -Sum).Sum) topics"
